import { check, report } from './lib.mjs';
import { C, GRAV, ADRIAN } from './constants.mjs';
const P = Math.PI, GM = GRAV.earthGM, G = GRAV.G, Re = C.earthRadius;
const vc = (gm, r) => Math.sqrt(gm / r), per = (gm, r) => 2 * P * Math.sqrt(r ** 3 / gm);
export default function () {
	const r1 = Re + GRAV.issAltitude;
	check('WE1 r', r1, 6.771e6, 0.0001); check('WE1 v', vc(GM, r1), 7670, 0.001); check('WE1 v 7673', vc(GM, r1), 7673, 0.0002);
	check('WE1 T s', per(GM, r1), 5545, 0.001); check('WE1 T min', per(GM, r1) / 60, 92.4, 0.001); check('WE1 laps', 86400 / per(GM, r1), 15.6, 0.003);
	check('WE1 fall', 0.5 * 8.69, 4.35, 0.002); check('WE1 curve', vc(GM, r1) ** 2 / (2 * r1), 4.35, 0.002); check('WE1 7.67 km', vc(GM, r1) / 1000, 7.67, 0.001);
	const v2 = Math.sqrt(C.earthGravityMean * Re);
	check('WE2 v', v2, 7910, 0.001); check('WE2 T', (2 * P * Re) / v2, 5060, 0.002); check('WE2 min', (2 * P * Re) / v2 / 60, 84.3, 0.001);
	const GMA = G * ADRIAN.mass, rA = ADRIAN.parkR;
	check('WE3 M', ADRIAN.mass, 2.347e25, 0.001); check('WE3 R', ADRIAN.radius / 1000, 9557, 0.0001); check('WE3 GM', GMA, 1.567e15, 0.001); check('WE3 r', rA, 9.857e6, 0.0001);
	check('WE3 v', vc(GMA, rA), 12600, 0.001); check('WE3 v2', vc(GMA, rA), 12610, 0.0005); check('WE3 T', per(GMA, rA), 4910, 0.002); check('WE3 min', per(GMA, rA) / 60, 81.9, 0.001);
	check('WE3 km/h', vc(GMA, rA) * 3.6, 45000, 0.02);
	const T4 = 86164, r4 = Math.cbrt((GM * T4 ** 2) / (4 * P * P));
	check('WE4 T', C.earthSiderealDay, T4, 0.0001); check('WE4 r', r4, 4.2164e7, 0.0002); check('WE4 vs ref', GRAV.geoRadius, r4, 0.0002);
	check('WE4 h', 42164 - 6378, 35786); check('WE4 v', (2 * P * r4) / T4, 3070, 0.002); check('WE4 %', (2 * P * r4) / T4 / vc(GM, r1), 0.4, 0.01);
	const GMT = G * 0.8 * C.sunMass, a5 = 0.552 * C.au;
	check('WE5 GM', GMT, 1.062e20, 0.001); check('WE5 r', 0.552 * 1.496e11, 8.258e10, 0.0002); check('WE5 v', vc(GMT, a5), 35900, 0.002);
	check('WE5 T s', per(GMT, a5), 1.447e7, 0.001); check('WE5 days', per(GMT, a5) / 86400, 167.5, 0.001); check('WE5 vs cat', GRAV.adrianPeriodDays, 167.5, 0.005);
	check('fig mountain', 128 / 105, 1.2, 0.02); check('sim esc', Math.SQRT2 * vc(GM, r1) / 1000, 10.85, 0.001);
	check('P1', vc(GM, C.moonDistance), 1018, 0.001); check('P1 vs NASA', 1018 / GRAV.moonOrbitSpeed, 0.995, 0.002);
	check('P3 v', 4 ** -0.5, 0.5); check('P3 T', 4 ** 1.5, 8);
	const v5 = vc(4.2828e13, GRAV.marsRadius);
	check('P5 v', v5, 3550, 0.002); check('P5 T', (2 * P * GRAV.marsRadius) / v5, 5990, 0.002); check('P5 min', (2 * P * GRAV.marsRadius) / v5 / 60, 100, 0.003);
	const T6 = per(GM, C.moonDistance);
	check('P6 T', T6, 2.372e6, 0.001); check('P6 d', T6 / 86400, 27.45, 0.001); check('P6 d M+m', per(GM * (1 + 1 / 81.3), C.moonDistance) / 86400, 27.29, 0.001);
	check('P6 vs measured', 27.29 / 27.3217, 0.999, 0.001); check('P6 err', 27.45 / 27.3217 - 1, 0.005, 0.1);
	check('P7', vc(1.32712e20, GRAV.venusSemiMajor), 35020, 0.001);
	const g8 = GMA / rA ** 2;
	check('P8 g', g8, 16.1, 0.003); check('P8 fall', 0.5 * g8, 8.06, 0.001); check('P8 curve', 12607 ** 2 / (2 * rA), 8.06, 0.001);
	check('P9 ω', Math.sqrt(GM / r1 ** 3), 1.13e-3, 0.003); check('P9 ratio', 0.3546 / Math.sqrt(GM / r1 ** 3), 300, 0.05);
	const w2 = GMA / rA ** 3, r10 = rA - 1e4, diff = GMA / r10 ** 2 - w2 * r10;
	check('P10 ω²', w2, 1.636e-6, 0.001); check('P10 r′', r10, 9.847e6, 0.0001); check('P10 diff', diff, 0.0491, 0.002); check('P10 approx', 3 * w2 * 1e4, 0.0491, 0.002);
	check('P10 T', 50 * diff, 2.5, 0.02); check('P10 W', 50 * 17.15, 860, 0.003);
	check('P11', (4 * P * P) / GM, 9.9e-14, 0.001); check('P11 ISS', 5545 ** 2 / r1 ** 3, 9.9e-14, 0.002);
	const r12 = Math.cbrt((GM * 7200 ** 2) / (4 * P * P));
	check('P12 r', r12, 8.06e6, 0.001); check('P12 h', r12 / 1000 - 6371, 1690, 0.003);
	return report('4.2 Orbital speed');
}
