import { check, report } from './lib.mjs';
import { C } from './constants.mjs';

const d2r = Math.PI / 180;
export default function () {
	check('1 rad in deg', 180 / Math.PI, 57.3, 1e-3);
	check('1 deg in rad', d2r, 0.01745, 1e-3);
	check('sin10 err', (Math.sin(10 * d2r) - 10 * d2r) / (10 * d2r), -0.005, 0.05);
	check('tan10 err', (Math.tan(10 * d2r) - 10 * d2r) / (10 * d2r), 0.0103, 0.05);
	check('atan 0.3', Math.atan(0.3) / d2r, 16.7, 0.005);
	check('WE1 h', 5 * Math.sin(70 * d2r), 4.70, 0.002);
	check('WE1 foot', 5 * Math.cos(70 * d2r), 1.71, 0.002);
	const sunAng = (2 * C.sunRadius) / C.earthSemiMajor;
	check('WE2 rad', sunAng, 9.30e-3, 0.002);
	check('WE2 deg', sunAng / d2r, 0.533, 0.002);
	check('WE2 NASA', 1919 / 3600, 0.533, 0.002);
	const p = (273.81e-3 / 3600) * d2r;
	check('WE3 p rad', p, 1.3275e-6, 1e-4);
	check('WE3 au', 1 / p, 7.533e5, 1e-3);
	check('WE3 m', (1 / p) * 1.496e11, 1.127e17, 1e-3);
	check('WE3 ly', ((1 / p) * C.au) / C.lightYear, 11.91, 1e-3);
	check('coin', 0.02 / 15000, p, 0.01);
	const sunFromTC = 1.391e9 / 1.127e17;
	check('WE4 rad', sunFromTC, 1.234e-8, 1e-3);
	check('WE4 mas', (sunFromTC / d2r) * 3.6e6, 2.55, 0.005);
	check('WE5 theta', (2 * Math.PI) / 365.25, 0.0172, 1e-3);
	check('WE5 s', 1.496e11 * ((2 * Math.PI) / 365.25), 2.574e9, 1e-3);
	check('WE5 v', (1.496e11 * ((2 * Math.PI) / 365.25)) / 86400, 2.979e4, 1e-3);
	check('P1b', 2 * (180 / Math.PI), 114.6, 1e-3);
	check('P1c', 0.5 * d2r, 8.73e-3, 1e-3);
	check('P2', Math.atan(0.75) / d2r, 36.9, 1e-3);
	check('P3 len', Math.hypot(1.2, 4.0), 4.18, 1e-3);
	check('P6', 3.475e6 / 3.844e8 / d2r, 0.518, 0.002);
	check('P7 rad', 5 * d2r, 0.08727, 1e-4);
	check('P7 sin err %', (100 * (Math.sin(5 * d2r) - 5 * d2r)) / (5 * d2r), -0.13, 0.03);
	check('P7 tan err %', (100 * (Math.tan(5 * d2r) - 5 * d2r)) / (5 * d2r), 0.25, 0.03);
	const p8 = (0.1 / 3600) * d2r;
	check('P8 rad', p8, 4.85e-7, 1e-3);
	check('P8 au', 1 / p8, 2.06e6, 0.002);
	check('P8 ly', 1 / p8 / 63240, 32.6, 0.002);
	check('P9 angle', 180 - Math.asin(0.6) / d2r, 143.13, 1e-4);
	check('P10', Math.atan(1 / 11.91) / d2r, 4.80, 0.002);
	check('P10 small', (1 / 11.91) / d2r, 4.81, 0.002);
	const perp = 6378 * Math.sin(40 * d2r), foot = 6378 * Math.cos(40 * d2r);
	check('P11 perp', perp, 4099.7, 1e-4);
	check('P11 foot', foot, 4885.9, 1e-4);
	check('P11 AS', Math.hypot(perp, 42164 - foot), 37503, 1e-4);
	check('P12', Math.cos(0.2), 0.98007, 1e-5);
	return report('0.6 Trigonometry');
}
