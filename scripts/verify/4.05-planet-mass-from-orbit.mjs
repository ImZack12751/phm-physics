import { check, report } from './lib.mjs';
import { C, GRAV, ADRIAN } from './constants.mjs';
const P = Math.PI, G = GRAV.G, Me = C.earthMass;
const M = (a, T) => (4 * P * P * a ** 3) / (G * T * T);
const tLow = (rho) => Math.sqrt((3 * P) / (G * rho));
export default function () {
	const T1 = C.moonSiderealMonth;
	check('WE1 T', T1, 2.3606e6, 0.0001); check('WE1 M', M(C.moonDistance, T1), 6.03e24, 0.002); check('WE1 1%', M(C.moonDistance, T1) / Me, 1.01, 0.002);
	check('WE1 Moon share', GRAV.moonMass / (Me + GRAV.moonMass), 0.012, 0.03);
	const T2 = GRAV.earthSiderealYear * 86400;
	check('WE2 T', T2, 3.1558e7, 0.0001); check('WE2 M', M(1.496e11, T2), 1.99e30, 0.002); check('WE2 ratio', C.sunMass / Me, 333000, 0.001);
	const MJ = M(421.8e6, 1.769138 * 86400);
	check('WE3 M', MJ, 1.9e27, 0.002); check('WE3 Earths', MJ / Me, 318, 0.002); check('WE3 NASA', GRAV.jupiterMass, 1.898e27, 0.001);
	const s4 = 9557 / 9857, th4 = 2 * Math.asin(s4) * (180 / P);
	check('WE4 θ', th4, 151.7, 0.0005); check('WE4 θ/2', th4 / 2, 75.83, 0.0002); check('WE4 sin', Math.sin((75.83 * P) / 180), 0.9696, 0.0001);
	check('WE4 R rounded', (300 * 0.9696) / 0.0304, 9570, 0.001); check('WE4 R exact', (300 * s4) / (1 - s4), 9557, 0.0002);
	const ds = Math.cos((75.83 * P) / 180) * ((0.05 * P) / 180);
	check('WE4 sensitivity', ds / s4 + ds / (1 - s4), 0.01, 0.35);
	const T4 = 81.87 * 60, M4 = M(ADRIAN.parkR, T4);
	check('WE4 T s', T4, 4912, 0.0001); check('WE4 M', M4, 2.35e25, 0.002); check('WE4 Earths', M4 / Me, 3.93, 0.001); check('WE4 vs model', M4 / ADRIAN.mass, 1, 0.001);
	check('WE4 ρ', ADRIAN.mass / ((4 / 3) * P * ADRIAN.radius ** 3), 6420, 0.001); check('WE4 g', (G * ADRIAN.mass) / ADRIAN.radius ** 2, 17.2, 0.003);
	check('WE5 T', 84.3 * 60, 5058, 0.0001); check('WE5 ρ', (3 * P) / (G * 5058 ** 2), 5520, 0.002); check('WE5 NASA', Me / ((4 / 3) * P * C.earthRadius ** 3), 5514, 0.001);
	check('fig Jupiter', tLow(1326) / 60, 172, 0.003); check('fig Moon', tLow(3340) / 60, 108, 0.004); check('fig Mars', tLow(3934) / 60, 100, 0.003);
	check('fig Venus', tLow(5243) / 60, 86, 0.006); check('fig Earth', tLow(5514) / 60, 84, 0.005); check('fig Adrian', tLow(6420) / 60, 78, 0.003);
	check('sim default r', 10 ** 3.994, 9860, 0.0005); check('sim default T min', 10 ** 0.135 * 60, 81.9, 0.003);
	check('P2', 1 / 2 ** 2, 0.25); check('P3', 3 * 2, 6);
	const T5 = 0.31891 * 86400;
	check('P4 T', T5, 27554, 0.0001); check('P4 M', M(9378e3, T5), 6.43e23, 0.002); check('P4 vs NASA', M(9378e3, T5) / GRAV.marsMass - 1, 0.0014, 0.5);
	const M5 = M(0.552 * 1.496e11, 168 * 86400);
	check('P5 M', M5, 1.58e30, 0.003); check('P5 Msun', M5 / C.sunMass, 0.795, 0.002);
	check('P6 T', 118 * 60, 7080); check('P6 M', M(1.837e6, 7080), 7.32e22, 0.002);
	const r7 = ADRIAN.radius + 1e6, T7 = 2 * P * Math.sqrt(r7 ** 3 / (G * ADRIAN.mass));
	check('P7 r', r7 / 1000, 10557, 0.0001); check('P7 T', T7 / 60, 90.75, 0.0005); check('P7 T s', 90.75 * 60, 5445); check('P7 M', M(1.0557e7, 5445), 2.35e25, 0.002);
	check('P8 T', tLow(3340), 6500, 0.002); check('P8 min', tLow(3340) / 60, 108, 0.004);
	check('P9', 3 * 1 + 2 * 0.1, 3.2);
	check('P11', (29780 ** 2 * 1.496e11) / G, 1.99e30, 0.002);
	check('P12 sin³', 0.9696 ** 3, 0.9115, 0.0002); check('P12 ρ', (3 * P) / (G * 4912 ** 2 * 0.9115), 6420, 0.002);
	return report('4.5 Finding a planet’s mass from an orbit');
}
